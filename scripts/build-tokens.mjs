// Builds design tokens from tokens/tokens.json (the single source of truth) into:
//   src/styles/tokens.css        :root CSS variables (imported in main.tsx so edits hot-reload)
//   src/styles/tokens.theme.css  Tailwind @theme mapping, so tokens become classes (bg-pink, text-ui, shadow-pop-md)
//   tokens/figma-sync.js         paste into Figma's plugin console to create/update Figma Variables
// Run: npm run tokens
import { readFileSync, writeFileSync } from 'node:fs'

const src = JSON.parse(readFileSync(new URL('../tokens/tokens.json', import.meta.url), 'utf8'))
const HEADER = '/* GENERATED by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit by hand. */\n'

// Flatten DTCG groups into [{ path: ['primitive','color','ink','900'], type, value, description }]
function flatten(node, path = [], inheritedType) {
  const type = node.$type ?? inheritedType
  if ('$value' in node) return [{ path, type, value: node.$value, description: node.$description }]
  return Object.entries(node)
    .filter(([k]) => !k.startsWith('$'))
    .flatMap(([k, v]) => flatten(v, [...path, k], type))
}
const tokens = flatten(src)
const byPath = new Map(tokens.map((t) => [t.path.join('.'), t]))
const aliasOf = (v) => (typeof v === 'string' && /^\{.+\}$/.test(v) ? v.slice(1, -1) : null)

// CSS names: primitives get a --p- prefix (never used in components); semantic tokens use Tailwind's namespaces
const cssName = (path) => {
  const [tier, group, ...rest] = path
  if (tier === 'primitive') return `--p-${group}-${rest.join('-')}`
  return `--${group}-${rest.join('-')}`
}
const cssValue = (t) => {
  const a = aliasOf(t.value)
  if (!a) return t.value
  if (!byPath.has(a)) throw new Error(`Unknown alias {${a}} in ${t.path.join('.')}`)
  return `var(${cssName(a.split('.'))})`
}

const primitives = tokens.filter((t) => t.path[0] === 'primitive')
const semantic = tokens.filter((t) => t.path[0] === 'semantic')
const line = (t) => `  ${cssName(t.path)}: ${cssValue(t)};${t.description ? ` /* ${t.description} */` : ''}`

writeFileSync(new URL('../src/styles/tokens.css', import.meta.url),
  `${HEADER}:root {\n  /* Primitives: raw values */\n${primitives.map(line).join('\n')}\n\n  /* Semantic: what each value is for */\n${semantic.map(line).join('\n')}\n}\n`)

writeFileSync(new URL('../src/styles/tokens.theme.css', import.meta.url),
  `${HEADER}/* Exposes semantic tokens to Tailwind. Restart the dev server after ADDING or RENAMING a token. */\n@theme inline {\n${semantic.map((t) => `  ${cssName(t.path)}: var(${cssName(t.path)});`).join('\n')}\n}\n`)

// ---------- Figma ----------
// Colors, sizes and font families become Variables. Shadows stay code-only (Figma uses Effect styles for those).
const figmaType = { color: 'COLOR', dimension: 'FLOAT', fontFamily: 'STRING' }
const figmaName = (path) => path.slice(1).join('/') // drop the tier: color/ink/900
const figmaTokens = tokens.filter((t) => figmaType[t.type]).map((t) => {
  const a = aliasOf(t.value)
  let value = t.value
  if (!a && t.type === 'dimension') value = parseFloat(t.value)
  if (!a && t.type === 'fontFamily') value = t.value.split(',')[0].replace(/"/g, '').trim()
  return {
    collection: t.path[0] === 'primitive' ? 'Primitives' : 'Semantic',
    name: figmaName(t.path),
    type: figmaType[t.type],
    value: a ? null : value,
    alias: a ? figmaName(a.split('.')) : null,
    description: t.description ?? '',
  }
})

const figmaScript = `// Make It Pop: sync Figma Variables from tokens/tokens.json
// GENERATED by scripts/build-tokens.mjs. Re-run \`npm run tokens\` after editing tokens.json, then paste again.
// How: Figma file > Plugins > Development > Open console > paste > Enter. Safe to run repeatedly (updates in place).
{
const TOKENS = ${JSON.stringify(figmaTokens)};

function hexToRgb(hex) {
  const n = parseInt(hex.slice(1), 16);
  return { r: ((n >> 16) & 255) / 255, g: ((n >> 8) & 255) / 255, b: (n & 255) / 255, a: 1 };
}

const existingCollections = await figma.variables.getLocalVariableCollectionsAsync();
const existingVars = await figma.variables.getLocalVariablesAsync();
const collections = {};
for (const name of ['Primitives', 'Semantic']) {
  collections[name] = existingCollections.find((c) => c.name === name) || figma.variables.createVariableCollection(name);
}
const vars = {};
let created = 0;
let updated = 0;
for (const t of TOKENS) {
  const col = collections[t.collection];
  let v = existingVars.find((x) => x.name === t.name && x.variableCollectionId === col.id);
  if (v) { updated++; } else { v = figma.variables.createVariable(t.name, col, t.type); created++; }
  v.description = t.description;
  vars[t.collection + ':' + t.name] = v;
}
for (const t of TOKENS) {
  const col = collections[t.collection];
  const v = vars[t.collection + ':' + t.name];
  const modeId = col.modes[0].modeId;
  if (t.alias) {
    const target = vars['Primitives:' + t.alias] || vars['Semantic:' + t.alias];
    v.setValueForMode(modeId, figma.variables.createVariableAlias(target));
  } else if (t.type === 'COLOR') {
    v.setValueForMode(modeId, hexToRgb(t.value));
  } else {
    v.setValueForMode(modeId, t.value);
  }
  // Semantic variables show up in pickers; primitives are hidden from fills so designers pick by meaning
  if (t.collection === 'Primitives') v.hiddenFromPublishing = true;
}
figma.notify('Make It Pop tokens: ' + created + ' created, ' + updated + ' updated');
console.log('Done. Created ' + created + ', updated ' + updated + '.');
}
`
writeFileSync(new URL('../tokens/figma-sync.js', import.meta.url), figmaScript)

console.log(`tokens: ${primitives.length} primitives, ${semantic.length} semantic, ${figmaTokens.length} Figma variables`)
